import download from '@/utils/download'
import { InternationalDynamicApi, InternationalDynamicVO } from '@/api/dataHub/businessGuide/internationaldynamic'
import InternationalDynamicForm from './InternationalDynamicForm.vue'

/** 国际行业动态 列表 */
defineOptions({ name: 'InternationalDynamic' })

const message = useMessage() // 消息弹窗
const { t } = useI18n() // 国际化

const loading = ref(true) // 列表的加载中
const list = ref<InternationalDynamicVO[]>([]) // 列表的数据
const total = ref(0) // 列表的总页数
const queryParams = reactive({
  pageNo: 1,
  pageSize: 10,
  internationalDynamicId: undefined,
  dynamicTitle: undefined,
  dynamicTitleEn: undefined,
  sourceCountry: undefined,
  dynamicSource: undefined,
  releaseTime: [],
  dynamicDetail: undefined,
  dynamicDetailEn: undefined,
  coverImgId: undefined,
  coverImgPath: undefined,
  dynamicStatus: undefined,
  createUser: undefined,
  createTime: [],
  updateUser: undefined,
  extCat1: undefined,
  extCat2: undefined,
  extCommon1: undefined,
  extCommon2: undefined,
  createTimeSys: [],
  updateTimeSys: []
})
const queryFormRef = ref() // 搜索的表单
const exportLoading = ref(false) // 导出的加载中

/** 查询列表 */
const getList = async () => {
  loading.value = true
  try {
    const data = await InternationalDynamicApi.getInternationalDynamicPage(queryParams)
    list.value = data.list
    total.value = data.total
  } finally {
    loading.value = false
  }
}

/** 搜索按钮操作 */
const handleQuery = () => {
  queryParams.pageNo = 1
  getList()
}

/** 重置按钮操作 */
const resetQuery = () => {
  queryFormRef.value.resetFields()
  handleQuery()
}

/** 添加/修改操作 */
const formRef = ref()
const openForm = (type: string, id?: number) => {
  formRef.value.open(type, id)
}

/** 删除按钮操作 */
const handleDelete = async (id: number) => {
  try {
    // 删除的二次确认
    await message.delConfirm()
    // 发起删除
    await InternationalDynamicApi.deleteInternationalDynamic(id)
    message.success(t('common.delSuccess'))
    // 刷新列表
    await getList()
  } catch {}
}

/** 导出按钮操作 */
const handleExport = async () => {
  try {
    // 导出的二次确认
    await message.exportConfirm()
    // 发起导出
    exportLoading.value = true
    const data = await InternationalDynamicApi.exportInternationalDynamic(queryParams)
    download.excel(data, '国际行业动态.xls')
  } catch {
  } finally {
    exportLoading.value = false
  }
}

/** 初始化 **/
onMounted(() => {
  getList()
})
</script>
