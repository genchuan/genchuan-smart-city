import download from '@/utils/download'
import { PolInterpretationApi, PolInterpretationVO } from '@/api/dataHub/businessGuide/polinterpretation'
import PolInterpretationForm from './PolInterpretationForm.vue'

/** 政策解读信息 列表 */
defineOptions({ name: 'PolInterpretation' })

const message = useMessage() // 消息弹窗
const { t } = useI18n() // 国际化

const loading = ref(true) // 列表的加载中
const list = ref<PolInterpretationVO[]>([]) // 列表的数据
const total = ref(0) // 列表的总页数
const queryParams = reactive({
  pageNo: 1,
  pageSize: 10,
  polInterpretationId: undefined,
  relatedPolType: undefined,
  relatedPolId: undefined,
  relatedPolTitle: undefined,
  interpretationTitle: undefined,
  interpretationContent: undefined,
  interpreterId: undefined,
  interpreterName: undefined,
  interpretationTime: [],
  interpretationStatus: undefined,
  attachId: undefined,
  attachPath: undefined,
  createUser: undefined,
  createTime: [],
  updateUser: undefined,
  extCat1: undefined,
  extCat2: undefined,
  extCommon1: undefined,
  extCommon2: undefined,
  createTimeSys: [],
  updateTimeSys: []
})
const queryFormRef = ref() // 搜索的表单
const exportLoading = ref(false) // 导出的加载中

/** 查询列表 */
const getList = async () => {
  loading.value = true
  try {
    const data = await PolInterpretationApi.getPolInterpretationPage(queryParams)
    list.value = data.list
    total.value = data.total
  } finally {
    loading.value = false
  }
}

/** 搜索按钮操作 */
const handleQuery = () => {
  queryParams.pageNo = 1
  getList()
}

/** 重置按钮操作 */
const resetQuery = () => {
  queryFormRef.value.resetFields()
  handleQuery()
}

/** 添加/修改操作 */
const formRef = ref()
const openForm = (type: string, id?: number) => {
  formRef.value.open(type, id)
}

/** 删除按钮操作 */
const handleDelete = async (id: number) => {
  try {
    // 删除的二次确认
    await message.delConfirm()
    // 发起删除
    await PolInterpretationApi.deletePolInterpretation(id)
    message.success(t('common.delSuccess'))
    // 刷新列表
    await getList()
  } catch {}
}

/** 导出按钮操作 */
const handleExport = async () => {
  try {
    // 导出的二次确认
    await message.exportConfirm()
    // 发起导出
    exportLoading.value = true
    const data = await PolInterpretationApi.exportPolInterpretation(queryParams)
    download.excel(data, '政策解读信息.xls')
  } catch {
  } finally {
    exportLoading.value = false
  }
}

/** 初始化 **/
onMounted(() => {
  getList()
})
</script>
